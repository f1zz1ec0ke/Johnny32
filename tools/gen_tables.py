#!/usr/bin/env python3
"""Generate johnny/src/tables.rs from the original executable.

The scheduler's data lives in SCRANTIC.EXE's data segment rather than in
RESOURCE.001: the scene catalogue, the walk routes and the walk paths. This
emits it as Rust so the port does not need the 16-bit binary at run time.

It is engine data -- weights, timings, positions and route coordinates -- in
the same category as the opcode tables, not artwork. The sprites and
backgrounds stay in RESOURCE.001, which is never redistributed.

    python3 tools/gen_tables.py > johnny/src/tables.rs
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import scheduler


def main():
    exe = sys.argv[1] if len(sys.argv) > 1 else 'original/scrantic.exe'
    data = scheduler.data_segment(exe)
    files = scheduler.ads_files(data)
    scenes = scheduler.scenes(data)
    steps = scheduler.walk_steps(exe, data)

    out = []
    w = out.append
    w('//! Scheduler tables, generated by `tools/gen_tables.py` from the')
    w('//! original executable. Do not edit by hand.')
    w('//!')
    w('//! These live in `SCRANTIC.EXE`\'s data segment rather than in')
    w('//! `RESOURCE.001`, so they are baked in here to keep the 16-bit binary')
    w('//! out of the run-time requirements. See `docs/SCHEDULER.md`.')
    w('')
    w('/// An entry in the scene catalogue at `ds:0x1756`.')
    w('pub struct Scene {')
    w('    /// Group id; several entries share one.')
    w('    pub id: u16,')
    w('    /// Selection weight.')
    w('    pub weight: u8,')
    w('    /// Position Johnny must be standing in. (0, _) means anywhere.')
    w('    pub from: (u8, u8),')
    w('    /// Position he ends up in.')
    w('    pub to: (u8, u8),')
    w('    /// Deducted from the caller\'s time budget.')
    w('    pub cost: u8,')
    w('    /// Time-of-day window: playable when `min <= phase < max`.')
    w('    pub min_phase: u8,')
    w('    pub max_phase: u8,')
    w('    /// Story day, or 0 for an everyday scene.')
    w('    pub day: u8,')
    w('    /// Category bitmask.')
    w('    pub mask: u32,')
    w('    /// ADS file id and the sequence within it. Sequence 0 is disabled.')
    w('    pub ads: u8,')
    w('    pub sequence: u8,')
    w('}')
    w('')
    w('/// ADS file ids to record names.')
    w('pub const ADS_FILES: &[(u8, &str)] = &[')
    for fid, name in sorted(files.items()):
        if name == '(none)' or fid > 255:
            continue
        w('    (%d, "%s"),' % (fid, name))
    w('];')
    w('')
    w('pub const SCENES: &[Scene] = &[')
    for s in scenes:
        w('    Scene { id: %d, weight: %d, from: (%d, %d), to: (%d, %d), cost: %d, '
          'min_phase: %d, max_phase: %d, day: %d, mask: %#x, ads: %d, sequence: %d },'
          % (s['id'], s['weight'], s['from'][0], s['from'][1], s['to'][0], s['to'][1],
             s['cost'], s['min'], s['max'], s['day'], s['mask'], s['ads'], s['seq']))
    w('];')
    w('')
    w('/// One option in a route block: a walk step and its weight.')
    w('pub struct RouteOption {')
    w('    pub step: u8,')
    w('    pub weight: u8,')
    w('}')
    w('')
    w('/// The route table: heading from `from` to `to`, and currently standing')
    w('/// at `at`, these are the walk steps available and their weights. A')
    w('/// missing row means there is nothing to do -- Johnny has arrived.')
    w('///')
    w('/// Every weight list totals 100, except the 1 -> 5 row at position 1,')
    w('/// which totals 150. See `docs/SCHEDULER.md`: the original draws')
    w('/// `rand() % 100` here, so its last two options never fire.')
    w('pub const ROUTE_TABLE: &[(u8, u8, u8, &[RouteOption])] = &[')
    import struct
    for f in range(1, 7):
        for t in range(1, 7):
            if f == t:
                continue
            off = struct.unpack_from('<H', data, scheduler.ROUTE_MATRIX + f * 12 + t * 2)[0]
            if not off:
                continue
            for pos, pairs in scheduler.route_block(data, off):
                real = [(s, wt) for s, wt in pairs if s != 0]
                if not real:
                    continue
                opts = ', '.join('RouteOption { step: %d, weight: %d }' % (s, wt)
                                 for s, wt in real)
                w('    (%d, %d, %d, &[%s]),' % (f, t, pos, opts))
    w('];')
    w('')
    w('/// A walk path: where it leaves Johnny, and the waypoints to get there.')
    w('pub struct WalkStep {')
    w('    pub id: u8,')
    w('    /// The facing the path starts from. `seg4:0x01CD` will not run the')
    w('    /// path until Johnny is turned this way, so he pivots on the spot')
    w('    /// first -- byte 0 of the triple at `ds:0x02DE`.')
    w('    pub face: u8,')
    w('    /// Position after the walk, as (major, minor).')
    w('    pub lands: (u8, u8),')
    w('    /// `(frame, x, y)`; bit 15 of the frame mirrors the sprite.')
    w('    pub path: &\'static [(u16, u16, u16)],')
    w('}')
    w('')
    w('pub const WALK_STEPS: &[WalkStep] = &[')
    for sid in sorted(steps):
        _, pts = steps[sid]
        a = data[scheduler.STEP_POSITIONS + sid * 3:scheduler.STEP_POSITIONS + sid * 3 + 3]
        path = ', '.join('(%d, %d, %d)' % p for p in pts)
        w('    WalkStep { id: %d, face: %d, lands: (%d, %d), path: &[%s] },'
          % (sid, a[0], a[2], a[1], path))
    w('];')
    w('')
    w('/// Standing poses, by area: the step id whose `path` is eight poses,')
    w('/// one per facing, rather than a walk.')
    w('///')
    w('/// `seg4:0x0223` takes the first when Johnny has reached the area he')
    w('/// was heading for and the second while he is still travelling, and')
    w('/// `seg4:0x0258` indexes it by the minor. Index 0 is unused.')
    w('pub const POSES: [(u8, u8); 7] = [')
    for major in range(7):
        w('    (%d, %d),' % (data[scheduler.POSE_HERE + major],
                             data[scheduler.POSE_ONWARD + major]))
    w('];')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
